"""Generate native SourceMod guides from guides.json without changing UTF-8 encoding."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]

def generate():
    if not (ROOT / 'guides.json').exists():
        print('Native guides are maintained in addons/sourcemod/scripting/include/shroudfire/guides.inc.')
        return
    guides = json.loads((ROOT / 'guides.json').read_text(encoding='utf-8'))
    markers = json.loads((ROOT / 'tools/guide-markers.json').read_text(encoding='utf-8'))
    source = '// Generated by tools/generate_guides.py; edit guides.json.\n'
    source += 'void BuildGuidePage(int guide,int page,char[] text,int length)\n{\n    switch (guide)\n    {\n'
    for number, name in enumerate(['kHelpPages', 'kUpgradePages', 'kKnownBugPages', 'kCheatPages']):
        source += f'        case {number}:\n        {{\n            switch (page % {len(guides[name])})\n            {{\n'
        for index, page in enumerate(guides[name]):
            source += f'                case {index}: strcopy(text,length,{json.dumps(page,ensure_ascii=False)});\n'
        source += '            }\n        }\n'
    source += '    }\n    char value[48];\n'
    for marker, cvar in markers.items():
        source += f'    FindConVar("sf_{cvar}").GetString(value,sizeof(value)); ReplaceString(text,length,"{{{marker}}}",value);\n'
    source += '    IntToString(g_CvarKnifeDamageMin.IntValue < g_CvarKnifeDamageMax.IntValue ? g_CvarKnifeDamageMin.IntValue : g_CvarKnifeDamageMax.IntValue,value,sizeof(value)); ReplaceString(text,length,"{KNIFE_LOW}",value);\n'
    source += '    IntToString(g_CvarKnifeDamageMin.IntValue > g_CvarKnifeDamageMax.IntValue ? g_CvarKnifeDamageMin.IntValue : g_CvarKnifeDamageMax.IntValue,value,sizeof(value)); ReplaceString(text,length,"{KNIFE_HIGH}",value);\n'
    source += '    ReplaceString(text,length,"{TIMEOUT_RESULT}",g_CvarTimeoutKillInvisant.BoolValue?"die.":"revealed.");\n}\n'
    target = ROOT / 'addons/sourcemod/scripting/include/shroudfire/guides.inc'
    target.write_bytes(source.encode('utf-8'))

if __name__ == '__main__':
    generate()
